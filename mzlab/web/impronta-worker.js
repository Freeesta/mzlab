// @ts-check
// @ts-strict
// Hashes the pieces of a member while the copy to OPFS goes on (impronta.js): `Passata` of the engine, one instance of the .wasm compiled by the worker of the engine and given with { op: "module" }.
// Messages only (no SharedArrayBuffer): { op: "new", id, size, noSha1?, onlySha1? }, { op: "upd", id, b } (answered with { op: "ack", id }), { op: "end", id, file? } (answered with { op: "fine", id, out }:
// with `file` the member is read from it, no pieces sent; with `tick` too, each piece read is told with { op: "read", id, n }).
// @ts-ignore the engine is generated by wasm-bindgen: it is not in the tree
import init, { Passata } from "./wasm/mzlab_wasm.js";

/** @type {Map<number, { fine: () => string[] | undefined, aggiorna: (b: Uint8Array) => void}>} */
const passate = new Map();
const STEP = 8 << 20;                                 // bytes read at a time from the copy (`end` with a file)
let ready = /** @type {Promise<unknown> | null} */ (null);
// the script and its engine glue are here: the page hashes in this worker from now on (impronta.js `up`)
postMessage({ op: "up" });
onmessage = async ev => {
  const m = ev.data;
  if (m.op === "module") { ready = (m.module ? init({ module_or_path: m.module }) : init()); return; }
  let broken = false;
  try { await ready; } catch (_) { broken = true; }
  // no engine here: the page takes the fingerprints later
  if (broken) { if (m.op === "upd") postMessage({ op: "ack", id: m.id }); else if (m.op === "end") postMessage({ op: "fine", id: m.id, out: null }); return; }
  try {
    if (m.op === "new") passate.set(m.id, new Passata(m.size, m.noSha1, m.onlySha1));
    else if (m.op === "upd") { passate.get(m.id)?.aggiorna(m.b); postMessage({ op: "ack", id: m.id }); }
    else if (m.op === "end") {
      const p = passate.get(m.id); passate.delete(m.id);
      // the next piece is read while this one is hashed; other members' messages go on meanwhile
      if (p && m.file) {
        const at = (/** @type {number} */ o) => o < m.file.size ? m.file.slice(o, o + STEP).arrayBuffer() : null;
        for (let o = 0, next = at(o); next; o += STEP) { const b = new Uint8Array(await next); next = at(o + STEP); p.aggiorna(b); if (m.tick) postMessage({ op: "read", id: m.id, n: b.length }); }
      }
      const out = p ? p.fine() : null;                  // `fine` consumes the object: nothing to free
      postMessage({ op: "fine", id: m.id, out: out ? Array.from(out) : null });
    }
  // the page takes the fingerprints later; never leave the copy waiting
  } catch (_) {
    if (m.op === "upd") postMessage({ op: "ack", id: m.id }); else if (m.op === "end") postMessage({ op: "fine", id: m.id, out: null });
  }
};
