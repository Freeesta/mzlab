// @ts-check
// SPIKE, off unless OPFS holds `mzlab/una-passata.on` (and the page is cross-origin isolated): ONE pass over a dropped plain mzML. The copy to OPFS
// (rust-carica.js copyPrints) hands each piece it writes to a builder worker started with the copy (idx-worker.js, op "stream") through a ring of
// SharedArrayBuffer slots; a piece that finds the ring full is skipped (the builder reads it from the dropped File). At the end of the copy the scan table
// is made here (prepare_upload on the copy) and goes through the same ring after the last byte of the file; lr_index takes the builder's answer (`result`). Rust: build_mzidx_streamed.

// @ts-ignore the engine is generated by wasm-bindgen: it is not in the tree
import { prepare_upload } from "./wasm/mzlab_wasm.js";
import { openSource } from "./lettura-sync.js";
import { earlyTicInputs } from "./idx-aiuti.js";
import { SLOTS, SLOT, C, HEAD } from "./una-passata-lettore.js";

/** whether the spike is on: shared memory, and the switch file in OPFS */
async function on() {
  if (!self.crossOriginIsolated || typeof SharedArrayBuffer === "undefined") return false;
  try { await (await (await navigator.storage.getDirectory()).getDirectoryHandle("mzlab")).getFileHandle("una-passata.on"); return true; } catch (_) { return false; }
}

/** the eight inputs of build_mzidx (prepare_upload's answer) as bytes: nine u32 (seven lengths, hr1, declared scans), then the parts @param {any[]} p */
function tableBytes(p) {
  const enc = new TextEncoder(), parts = [p[0], p[1], p[2], p[3], p[4], enc.encode(p[5]), enc.encode(p[6])];
  const u = new Uint8Array(HEAD + parts.reduce((s, x) => s + x.byteLength, 0)), h = new Uint32Array(u.buffer, 0, 9);
  let at = HEAD;
  parts.forEach((x, i) => { h[i] = x.byteLength; u.set(new Uint8Array(x.buffer, x.byteOffset, x.byteLength), at); at += x.byteLength; });
  h[7] = p[7] ? 1 : 0; h[8] = +p[9] || 0;
  return u;
}

// the ring's events: a push or a freed slot wakes the other side
const wake = (/** @type {Int32Array} */ ctrl) => { Atomics.add(ctrl, C.SEQ, 1); Atomics.notify(ctrl, C.SEQ); };
const waitSeq = async (/** @type {Int32Array} */ ctrl, /** @type {number} */ seq) => {
  const w = /** @type {any} */ (Atomics).waitAsync;
  if (w) { const r = w(ctrl, C.SEQ, seq, 1000); if (r.async) await r.value; } else await new Promise(r => setTimeout(r, 2));
};

function push(/** @type {any} */ job, /** @type {Uint8Array} */ b, /** @type {number} */ off) {
  const ctrl = /** @type {Int32Array} */ (job.ctrl), k = Atomics.load(ctrl, C.PUSH) % SLOTS;
  job.data.set(b, k * SLOT); job.meta[2 * k] = off; job.meta[2 * k + 1] = b.length;
  Atomics.add(ctrl, C.PUSH, 1); wake(ctrl);
}
// the table (offsets after the file), as the builder frees the slots
async function feed(/** @type {any} */ job, /** @type {Uint8Array} */ t) {
  const ctrl = /** @type {Int32Array} */ (job.ctrl), size = job.size;
  for (let at = 0; at < t.length && !Atomics.load(ctrl, C.STOP);) {
    const seq = Atomics.load(ctrl, C.SEQ);
    if (Atomics.load(ctrl, C.PUSH) - Atomics.load(ctrl, C.TAKE) >= SLOTS) { await waitSeq(ctrl, seq); continue; }
    push(job, t.subarray(at, Math.min(at + SLOT, t.length)), size + at); at += SLOT;
  }
}

/** @param {{ conf: () => { budget?: number, cap?: number, module?: any, aiuti?: number } }} h */
export function createUnaPassata({ conf }) {
  /** @type {Map<string, any>} */ const jobs = new Map();

  /** a builder for `m` (a plain .mzML being copied), or null when the spike is off @param {{ blob: Blob, name: string }} m */
  async function start(m) {
    if (!/\.mzml$/i.test(m.name) || !(await on())) return null;
    const ctrl = new Int32Array(new SharedArrayBuffer(4 * 8)), meta = new Float64Array(new SharedArrayBuffer(8 * 2 * SLOTS)), data = new Uint8Array(new SharedArrayBuffer(SLOT * SLOTS));
    const c = conf(), t0 = performance.now();
    const w = new Worker(new URL("./idx-worker.js", import.meta.url), { type: "module" });
    const job = { name: m.name, size: m.blob.size, blob: m.blob, ctrl, meta, data, live: 0, ended: false, sink: /** @type {any} */ (null), early: /** @type {any} */ (null), last: /** @type {any} */ (null), w, res: /** @type {any} */ (null) };
    job.res = new Promise(resolve => {
      w.onmessage = ev => {
        const r = ev.data;
        if (r.op === "progress") { if (job.ended) { job.last = r; if (job.sink) job.sink(r); } return; }      // the bar of the copy is the copy's until it ends
        if (r.op === "done") resolve({ ok: true, stats: r.stats, ms: Math.round(performance.now() - t0) });
        else if (r.op === "error") resolve(r.fatal ? null : { ok: false, reason: "error", text: r.text });
        else if (r.op === "unavailable") resolve(null);
        else return;
        Atomics.store(ctrl, C.STOP, 1); w.terminate();      // the feeding ends with the builder and closes its handle on the copy
      };
      w.onerror = () => { resolve(null); Atomics.store(ctrl, C.STOP, 1); w.terminate(); };
    });
    w.postMessage({ op: "module", module: c.module || null });
    w.postMessage({ op: "stream", name: m.name, blob: m.blob, part: m.name + ".mzidx.part", budget: c.budget || 64, cap: c.cap || 0, aiuti: c.aiuti || 0, ring: { ctrl, meta, data } });
    jobs.set(m.name, job);
    return {
      /** a piece the copy wrote at `off`: into the ring if there is room (never waits: the copy keeps its pace) */
      add(/** @type {Uint8Array} */ b, /** @type {number} */ off) {
        if (b.length > SLOT || Atomics.load(ctrl, C.PUSH) - Atomics.load(ctrl, C.TAKE) >= SLOTS) return;
        push(job, b, off); job.live++;
      },
      /** the copy is done (`prints` = [sha256, sha1, probe]): the builder reads the rest from the File, the scan table follows through the ring */
      async end(/** @type {any} */ prints) {
        job.ended = true; Atomics.store(ctrl, C.DONE, 1); wake(ctrl);
        const fonte = await openSource("files", m.name, m.blob);
        let t;
        try {
          const p = Array.from(prepare_upload(job.size, (/** @type {number} */ o, /** @type {number} */ n) => fonte.read(o, n), m.name, prints && prints[0], prints && prints[2], c.cap || 0));
          t = tableBytes(p); job.early = earlyTicInputs(p.slice(0, 8));
        } catch (e) { Atomics.store(ctrl, C.FAIL, 1); wake(ctrl); throw e; } finally { fonte.close(); }
        feed(job, t);
      },
      abort() { stop(job); },
    };
  }

  function stop(/** @type {any} */ job) { Atomics.store(job.ctrl, C.STOP, 1); wake(job.ctrl); job.w.terminate(); jobs.delete(job.name); }

  return {
    start,
    /** lr_index of `name`: the answer of its one-pass builder (the shape of idxPool().build), or null when there is none or it failed (the pool builds it as before) */
    async result(/** @type {string} */ name, /** @type {(p: any) => void} */ onProgress) {
      const job = jobs.get(name);
      if (!job) return null;
      jobs.delete(name);
      job.sink = onProgress;
      if (job.early) onProgress({ frac: 1, phase: "scan", done: 0, total: job.early.rt.length, early_tic: job.early });
      if (job.last) onProgress(job.last);
      const r = await job.res;
      if (r && r.ok) console.info("una-passata " + JSON.stringify({ ...r.stats, live: job.live }));      // the measurement (tests_e2e/misura_una_passata.py) reads whether the one pass held and how many pieces came during the copy
      return r;
    },
    cancel(/** @type {string} */ name) { const job = jobs.get(name); if (job) stop(job); },
  };
}
