"""Write the nuclide table of the engine (crates/mzlab-core/src/nuclidi.rs): for every element from H the exact mass of the isotopes OpenChemLib knows,
and the mass number of its monoisotopic isotope (the most abundant natural one; the longest-lived for the elements without a stable isotope;
Rf to Mt, whose longest-lived isotope OpenChemLib does not list, are left out). Only the isotopes within WINDOW mass numbers of the natural ones (of the monoisotopic
one for the elements without a stable isotope) are kept: the labels people draw (2H, 3H, 11C, 14C, 18F, 32P, 123I to 131I, 137Cs, 99Tc) and a grafo .wasm that stays small.

Sources, already in the program: exact masses from the isotope table inside OpenChemLib (tools/genera_elementi.py `ocl_masses`); natural abundances from
`AB` there; the mass numbers of the elements outside `AB` are typed below (IUPAC/CIAAW most abundant isotope, or the conventional longest-lived one).
A mass is stored as mass - A in units of 1e-9 u (an i32: the 9 decimals of OpenChemLib, exactly).
Run from the project root:  python3 tools/genera_nuclidi.py   (no rustfmt: the table is `rustfmt::skip`, sixteen values per line)
"""
from pathlib import Path

from genera_elementi import AB, SYMBOLS, ocl_masses

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "mzlab-core" / "src" / "nuclidi.rs"
MONO_A = {"Kr": 84, "Zr": 90, "Tc": 98, "Ru": 102, "Pd": 106, "In": 115, "Te": 130, "Xe": 132, "La": 139, "Ce": 140, "Nd": 142, "Pm": 145, "Sm": 152,
          "Eu": 153, "Gd": 158, "Dy": 164, "Er": 166, "Yb": 174, "Lu": 175, "Hf": 180, "Ta": 181, "W": 184, "Re": 187, "Os": 192, "Ir": 193, "Pt": 195,
          "Po": 209, "At": 210, "Rn": 222, "Fr": 223, "Ra": 226, "Ac": 227, "Th": 232, "Pa": 231, "U": 238, "Np": 237, "Pu": 244, "Am": 243, "Cm": 247,
          "Bk": 247, "Cf": 251, "Es": 252, "Fm": 257, "Md": 258, "No": 259, "Lr": 262, "Hs": 269}
WINDOW = 4


def rows():
    iso, out = ocl_masses(), []
    for z, sym in enumerate(SYMBOLS[:len(iso)], start=1):
        masses = {n + z: m for n, m in iso[z - 1].items()}
        mono = max(AB[sym].items(), key=lambda x: x[1])[0] if sym in AB else MONO_A.get(sym)
        if not masses or mono not in masses:
            continue
        nat = list(AB[sym]) if sym in AB else [mono]
        a0, a1 = max(min(masses), min(nat) - WINDOW), min(max(masses), max(nat) + WINDOW)
        if any(a not in masses for a in range(a0, a1 + 1)):
            raise SystemExit(f"{sym}: gap in the mass numbers")
        out.append((sym, mono, a0, [round((masses[a] - a) * 1e9) for a in range(a0, a1 + 1)]))
    return out


def main():
    t = rows()
    rs = ["//! Nuclides of the elements from H (generated by tools/genera_nuclidi.py: do not edit by hand). Per element: symbol, mass number of the",
          "//! monoisotopic isotope, first mass number, then (mass - A) in 1e-9 u of every isotope from there on.", "",
          "#[rustfmt::skip]", f"pub static NUCLIDES: [(&str, u16, u16, &[i32]); {len(t)}] = ["]
    for sym, mono, a0, d in t:
        chunks = [", ".join(str(x) for x in d[i:i + 16]) for i in range(0, len(d), 16)]
        rs.append(f'    ("{sym}", {mono}, {a0}, &[' + (chunks[0] + "]),") if len(chunks) == 1 else f'    ("{sym}", {mono}, {a0}, &[')
        if len(chunks) > 1:
            rs += [f"        {c}," for c in chunks] + ["    ]),"]
    rs.append("];")
    OUT.write_text("\n".join(rs) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(t)} elements, {sum(len(r[3]) for r in t)} nuclides")


if __name__ == "__main__":
    main()
