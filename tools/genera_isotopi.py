"""Write the isotope table of the elements beyond the core 13 of isoscore (Rust: crates/mzlab-core/src/isotable.rs; Python reference: mzlab/chem/isotable.py).

Same sources as tools/genera_elementi.py (exact masses from OpenChemLib, natural abundances typed there); an element with an isotope without a known mass is left out.
Run from the project root:  python3 tools/genera_isotopi.py
"""
from pathlib import Path

from genera_elementi import AB, SYMBOLS, ocl_masses

ROOT = Path(__file__).resolve().parents[1]
CORE = {"H", "C", "N", "O", "F", "Na", "Si", "P", "S", "Cl", "K", "Br", "I"}     # in isoscore.rs / isoscore.py by hand


def table():
    iso, out = ocl_masses(), []
    for z, sym in enumerate(SYMBOLS, start=1):
        if sym in CORE or sym not in AB:
            continue
        masses = iso[z - 1] if z - 1 < len(iso) else {}
        row = [(masses.get(a - z), round(pct / 100, 8)) for a, pct in sorted(AB[sym].items())]
        if all(m is not None for m, _ in row):
            out.append((sym, row))
    return out


def main():
    t = table()
    rs = ["//! Isotopes of the elements beyond the core table of `isoscore` (generated by tools/genera_isotopi.py: do not edit by hand).", "",
          f"pub const EXTRA: [(&str, &[(f64, f64)]); {len(t)}] = ["]
    rs += [f'    ("{s}", &[{", ".join(f"({m!r}, {p!r})" for m, p in r)}]),' for s, r in t] + ["];", ""]
    (ROOT / "crates/mzlab-core/src/isotable.rs").write_text("\n".join(rs))
    py = ['"""Isotopes of the elements beyond the core table of isoscore (generated by tools/genera_isotopi.py: do not edit by hand)."""', "", "EXTRA = {"]
    py += [f'    "{s}": [{", ".join(f"({m!r}, {p!r})" for m, p in r)}],' for s, r in t] + ["}", ""]
    (ROOT / "mzlab/chem/isotable.py").write_text("\n".join(py))
    print(len(t), "elements")


if __name__ == "__main__":
    main()
