"""Builds mzlab/web/teoria/indice-ricerca.js, the static index behind the search of the Teoria (teoria/cerca.js).

Entries: chapter and Pratica page titles, h2/h3 sections (anchor = the id teoria.js gives them at run time), glossary terms
(anchors added to the <dt> of 21-glossario.html), titles of the boxes (.box.gym and the Verifica sections) and the Pratica games.
Each entry is [text, type, url, chapter label, normalised search string]. Deterministic.

  python3 tools/genera_indice_teoria.py             write the file
  python3 tools/genera_indice_teoria.py --controlla  fail if the file on disk is not up to date (tests, CI)
"""
import html as htmllib
import json
import re
import sys
import unicodedata
from pathlib import Path

D = Path(__file__).resolve().parents[1] / "mzlab" / "web" / "teoria"
OUT = D / "indice-ricerca.js"
APP = re.search(r'APP_NAME = "([^"]+)"', (D.parent / "appname.js").read_text(encoding="utf-8")).group(1)

# extra search words: if the normalised text of an entry contains the key, the listed words are searchable too
SINONIMI = {
    "esi": ["elettrospray", "electrospray"],
    "elettrospray": ["esi", "electrospray"],
    "perdit": ["neutral loss", "perdita neutra"],
    "addott": ["adduct", "m+h", "m+na"],
    "ms2": ["msms", "ms/ms", "tandem", "frammentazione"],
    "msms": ["ms2", "tandem"],
    "frammentazione": ["frammentare", "fragmentation", "cid"],
    "alta risoluzione": ["hrms", "orbitrap", "tof"],
    "triplo quadrupolo": ["qqq", "qtrap", "mrm"],
    "mrm": ["transizione", "srm"],
    "ione molecolare": ["m+.", "molecular ion"],
    "isotop": ["cloro", "bromo", "a+2"],
    "formula": ["massa esatta", "ppm"],
    "ei": ["ionizzazione elettronica", "70 ev"],
    "ionizzazione elettronica": ["ei"],
    "ionizzazione chimica": ["ci"],
    "azoto": ["parita", "nitrogen rule"],
    "gradiente": ["fase mobile", "eluizione"],
    "cromatogramma": ["xic", "tic", "rt", "tempo di ritenzione"],
    "xic": ["cromatogramma estratto"],
    "tic": ["cromatogramma totale"],
}


def norm(s: str) -> str:
    s = unicodedata.normalize("NFD", s.lower())
    s = re.sub("[̀-ͯ]", "", s)
    return re.sub(r"\s+", " ", s).strip()


def slug(s: str) -> str:
    """Same rule as slug() in teoria.js (ids of the h2/h3)."""
    s = unicodedata.normalize("NFD", s.lower())
    s = re.sub("[̀-ͯ]", "", s)
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:48]


def plain(h: str) -> str:
    h = re.sub(r"<[^>]+>", "", h)
    return re.sub(r"\s+", " ", htmllib.unescape(h)).strip()


def chapters() -> list[tuple[str, str, str]]:
    src = (D / "teoria.js").read_text(encoding="utf-8")
    block = src[src.index("const CHAPTERS = ["):src.index("];", src.index("const CHAPTERS = ["))]
    out = []
    for f, n, t, _p in re.findall(r'\["([^"]+)", "([^"]+)", "([^"]+)", "([^"]+)"\]', block):
        out.append((f, n, t.replace("{APP}", APP)))
    return out


def label(n: str) -> str:
    return f"Cap. {n}" if n.isdigit() and n != "0" else "Guida"


def entry(text, kind, url, cap, extra=""):
    key = norm(text + " " + extra)
    syn = sorted({w for k, ws in SINONIMI.items() if re.search(r"(^| )" + re.escape(k), key) for w in ws} - {key})
    return [text, kind, url, cap, " ".join([key] + syn).strip()]


def build() -> list[list[str]]:
    out = []
    for f, n, title in chapters():
        src = (D / f).read_text(encoding="utf-8")
        cap = "Pratica" if n.startswith("P") else label(n)
        full = (f"{n}. " if n.isdigit() and n != "0" else "") + title
        out.append(entry(full, "pratica" if cap == "Pratica" else "capitolo", f, cap))
        last = ""
        for m in re.finditer(r'<h([23])(?: [^>]*?id="([^"]+)")?[^>]*>(.*?)</h\1>|<div class="box ([^"]*)"[^>]*><b>(.*?)</b>|<div class="sim" id="([^"]+)"[^>]*><h4>(.*?)</h4>', src, re.S):
            if m.group(3) is not None:
                t = plain(m.group(3))
                if not t:
                    continue
                last = m.group(2) or slug(t)
                out.append(entry(t, "sezione", f"{f}#{last}", cap))
            elif m.group(6):
                out.append(entry(plain(m.group(7)), "simulazione", f"{f}#{m.group(6)}", cap))
            else:
                classes, t = m.group(4).split(), plain(m.group(5))
                if "gym" in classes and t:
                    out.append(entry(t, "esercizio", f"{f}#{last}" if last else f, cap))
    g = (D / "21-glossario.html").read_text(encoding="utf-8")
    for i, dt in re.findall(r'<dt id="([^"]+)">(.*?)</dt>', g, re.S):
        out.append(entry(plain(dt), "glossario", f"21-glossario.html#{i}", "Glossario"))
    return out


def render(entries) -> str:
    return ("// Generated by tools/genera_indice_teoria.py: do not edit by hand.\n"
            "// [text, type, url, chapter, normalised search string]\n"
            "const INDICE_RICERCA = [\n" + ",\n".join(json.dumps(e, ensure_ascii=False) for e in entries) + "\n];\n")


def main() -> int:
    text = render(build())
    if "--controlla" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("indice-ricerca.js non aggiornato: python3 tools/genera_indice_teoria.py")
            return 1
        print("indice-ricerca.js aggiornato")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(len(text.splitlines()) - 3, "voci")
    return 0


if __name__ == "__main__":
    sys.exit(main())
