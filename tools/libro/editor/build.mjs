// Builds mzlab/web/vendor/libro/{editor-bundle.js,editor-bundle.css,fonts/}. Run: cd tools/libro/editor && npm install && npm run build
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { copyFileSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../../mzlab/web/vendor/libro");
rmSync(out, { recursive: true, force: true });

// KaTeX lists woff2, woff and ttf for every font: keep woff2 only (all browsers of the site support it)
const woff2Only = {
  name: "katex-woff2-only",
  setup(b) {
    b.onLoad({ filter: /katex\.min\.css$/ }, (a) => ({
      contents: readFileSync(a.path, "utf8").replace(/,url\([^)]*\.woff\) format\("woff"\),url\([^)]*\.ttf\) format\("truetype"\)/g, ""),
      loader: "css",
      resolveDir: path.dirname(a.path),
    }));
  },
};

const js = await build({
  entryPoints: { "editor-bundle": path.join(here, "entry.js") },
  bundle: true, minify: true, format: "iife", outdir: out, legalComments: "none", metafile: true,
  loader: { ".woff2": "file", ".ttf": "file", ".woff": "file" }, assetNames: "fonts/[name]",
  absWorkingDir: here,
});
await build({
  entryPoints: { "editor-bundle": path.join(here, "style.css") },
  bundle: true, minify: true, outdir: out, plugins: [woff2Only],
  loader: { ".woff2": "file", ".ttf": "file", ".woff": "file" }, assetNames: "fonts/[name]",
  absWorkingDir: here,
});

// licence list of every npm package that ended up in the JS bundle
const pkgs = new Map();
for (const f of Object.keys(Object.values(js.metafile.outputs)[0].inputs)) {
  const m = f.match(/^(?:\.\.\/)*(.*node_modules\/((?:@[^/]+\/)?[^/]+))/);
  if (!m || pkgs.has(m[2])) continue;
  const j = JSON.parse(readFileSync(path.join(here, m[1], "package.json"), "utf8"));
  pkgs.set(m[2], `${m[2]}@${j.version}\t${typeof j.license === "string" ? j.license : JSON.stringify(j.license)}`);
}
writeFileSync(path.join(out, "THIRD-PARTY.txt"), "npm packages bundled in editor-bundle.js (name@version, licence), generated by tools/libro/editor/build.mjs\n" + [...pkgs.values()].sort().join("\n") + "\n");
copyFileSync(path.join(here, "node_modules/@milkdown/crepe/LICENSE"), path.join(out, "LICENSE-milkdown.txt"));
copyFileSync(path.join(here, "node_modules/katex/LICENSE"), path.join(out, "LICENSE-katex.txt"));
