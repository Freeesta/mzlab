"""Writes docs/actions.md, the encyclopedia of the actions that change state, from COMMANDS_TAB in mzlab/web/commands.js (never by hand).

    python3 tools/doc_commands.py          # rewrite the page
    python3 tools/doc_commands.py --check  # exit 1 if the page is not the one the table gives (tests/test_comandi.py)
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import lang_catalog  # noqa: E402
JS = ROOT / "mzlab" / "web" / "commands.js"
OUT = ROOT / "docs" / "actions.md"
UNDO = {
    "snapshot": "undo with a snapshot (history.js)", "command": "command: do / undo handler (commands.js)", "removed": "removal with its own undo / redo (HISTORY.removed)",
    "layout": "arrangement of the panels (arrange.js)", "flow": "own stack of the Flow (S.undo)", "draw": "own stack of the editor (Ketcher)",
    "to-port": "NOT undoable yet", "none": "not undone",
}


def tabella() -> list[dict]:
    """The rows of COMMANDS_TAB: the text between TAB-BEGIN and TAB-END is a plain literal, evaluated by node."""
    src = JS.read_text(encoding="utf-8")
    body = src.split("// TAB-BEGIN", 1)[1].split("// TAB-END", 1)[0]
    r = subprocess.run(["node", "-e", body + "\nconsole.log(JSON.stringify(COMMANDS_TAB))"], capture_output=True, text=True, encoding="utf-8", check=True)
    return json.loads(r.stdout)


def etichette(lang: str) -> dict[str, str]:
    return lang_catalog.catalog(lang)


def pagina() -> str:
    rows, it = tabella(), etichette("en")
    o = ["# Actions that change state (generated)", "",
         "Generated by `python3 tools/doc_commands.py` from the `COMMANDS_TAB` table of `mzlab/web/commands.js`: do not edit by hand. "
         "Every action that changes state in the Data view is in the table; `tests/test_comandi.py` checks it.", "",
         "| Id | Name | Module | What the user chooses | State that changes | Key | Steps | Undo |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        und = UNDO[r["undo"]] + (f": {r['reason']}" if r.get("reason") else "")
        o.append(f"| `{r['id']}` | {it.get(r['name'], r['name'])} (`{r['name']}`) | `{r['module']}` | {r['params']} | {', '.join(r['fields']) or '-'} | {r['key'] or '-'} | {r['merge'] or '-'} | {und} |")
    n = sum(r["undo"] == "to-port" for r in rows)
    o += ["", f"To bring into the stack: {n} actions out of {len(rows)}.", ""]
    return "\n".join(o)


def main() -> int:
    if not shutil.which("node"):
        print("node not available")
        return 0 if "--check" in sys.argv else 1
    testo = pagina()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == testo else 1
    OUT.write_text(testo, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
