#!/usr/bin/env python3
"""Globals for tsc (job «tipi»): writes tools/tipi/globali.d.ts and globali-nomi.d.ts from the classic scripts listed in pagina.json.

globali.d.ts  = `declare var X: any` for every `window.X = ...` and for the names of the classic scripts that tsc reads as CommonJS (module.exports).
globali-nomi.d.ts = `declare var X: any` for every top-level name of the classic scripts, for the projects that do not include them (moduli, worker).
stretto.json/stretto2.json/stretto3.json (pagina/moduli) and stretto-worker.json/stretto2-worker.json/stretto3-worker.json (worker) = the files marked `// @ts-strict` (first lines), checked with `strict` (no noImplicitAny; catch variables `unknown` in stretto2*, `any` in TP_Mine/flow): they must have 0 errors.
stretto3*.json = the files marked `// @ts-noany` as well (first lines): `strict` plus `noImplicitAny`, catch variables `unknown`; 0 errors, a marked file that gets an implicit `any` back fails the job.
The generated files are git-ignored: controlla_tsc.py runs this script before every type check, so they are never stale and never conflict between PRs.
`--controlla` writes nothing and exits 1 when: a file of mzlab/web or TP_Mine is in no project, or a top-level name is defined in two classic scripts.
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TYPES = os.path.join(ROOT, "tools", "tipi")
NON_CONTROLLATI = ("mzlab/web/vendor/", "mzlab/web/esempi/", "mzlab/web/wasm/", "mzlab/web/lang/it/", "mzlab/web/lang/en/")


def read_list(nome):
    """Source files of a project (paths from the repository root, in the order of the file)."""
    with open(os.path.join(TYPES, nome + ".json")) as f:
        return [p[6:] for p in json.load(f)["include"] if p.startswith("../../")]


def read(p):
    with open(os.path.join(ROOT, p), encoding="utf8") as f:
        return f.read()


def first_level_names(text):
    ris = set()   # a one-line JSDoc may precede the declaration
    for m in re.finditer(r"^(?:/\*\*.*?\*/\s*)?(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)", text, re.M):
        ris.add(m.group(1))
    for row in re.finditer(r"^(?:/\*\*.*?\*/\s*)?(?:const|let|var)\s[^\n]*", text, re.M):   # const A = {...}, B = null, C = 0 ...: every name after a value
        for m in re.finditer(r"(?:[}\])]|\bnull|\btrue|\bfalse|\d|[\"'])\s*,\s*([A-Za-z_$][\w$]*)\s*=(?=[^=>])", row.group(0)):
            ris.add(m.group(1))
    return ris


def manuali():
    return set(re.findall(r"^declare (?:var|const|function|class) ([A-Za-z_$][\w$]*)", read("tools/tipi/manuale.d.ts"), re.M))


ASSIGN = r"\b(?:window|globalThis|self|root)\)?\.([A-Za-z_$][\w$]*)\s*=[^=]"


def genera():
    classici = read_list("pagina")
    window, window_classic, cjs, dove = set(), set(), set(), {}
    for p in classici:
        t = read(p)
        window |= set(re.findall(ASSIGN, t))
        window_classic |= set(re.findall(ASSIGN, t))
        n = first_level_names(t)
        if re.search(r"\bmodule\.exports\b", t):   # tsc reads these as CommonJS modules: their names are not global for it
            cjs |= n
        for x in n:
            dove.setdefault(x, []).append(p)
    for p in read_list("moduli"):
        window |= set(re.findall(ASSIGN, read(p)))
    in_code = {x for x, ps in dove.items() if not all(re.search(r"\bmodule\.exports\b", read(p)) for p in ps)}
    declared = (window | cjs) - in_code - manuali()
    head = "// GENERATED by tools/tipi/genera_globali.py (python3 tools/tipi/genera_globali.py): do not edit.\n"
    g = head + "".join("declare var %s: any;\n" % x for x in sorted(declared))
    su_window = sorted(window_classic & in_code - manuali())   # const X ... window.X = X: window.X has the type of X
    if su_window:
        g += "interface Window {\n" + "".join("  %s: typeof %s;\n" % (x, x) for x in su_window) + "}\n"
    n = head + "".join("declare var %s: any;\n" % x for x in sorted(set(dove) - manuali()))
    return g, n, dove


STRICT_HEADER = "// @ts-strict"
NOANY_HEAD = "// @ts-noany"


LIBERI = ("TP_Mine/", "flow/")   # kept at level 1 (catch variables `any`) until their owners close


def strict(progetti=("pagina", "moduli"), lib=("ES2022", "DOM", "DOM.Iterable"), tipi=("globali.d.ts", "globali-nomi.d.ts", "modello.d.ts", "manuale.d.ts", "manuale-dom.d.ts"), livello=1):
    """tools/tipi/stretto*.json: the files of the given projects with `// @ts-strict` in their first lines, checked with `strict` (noImplicitAny stays off from base.json).
    Level 1 = TP_Mine/ and flow/ files, catch variables stay `any`; level 2 = all the others, catch variables are `unknown`;
    level 3 = files that also have `// @ts-noany` (any folder), with noImplicitAny on. No file is in two levels."""
    files = []
    for nome in progetti:
        for p in read_list(nome):
            head = "\n".join(read(p).split("\n")[:3])
            if STRICT_HEADER not in head:
                if NOANY_HEAD in head:
                    raise SystemExit(f"{p}: `// @ts-noany` needs `// @ts-strict` in the first 3 lines too")
                continue
            mio = 3 if NOANY_HEAD in head else (1 if p.startswith(LIBERI) else 2)
            if mio == livello:
                files.append("../../" + p)
    options = {"lib": list(lib), "moduleDetection": "force", "strict": True, "useUnknownInCatchVariables": livello >= 2, "strictNullChecks": True}
    if livello == 3:
        options["noImplicitAny"] = True
    return json.dumps({"extends": "./base.json", "compilerOptions": options, "include": list(tipi) + files}, indent=2) + "\n"


def strict_worker(livello=1):
    return strict(("worker",), ("ES2022", "WebWorker"), ("manuale.d.ts", "manuale-worker.d.ts"), livello)


def strict_all():
    """{file name: content} of the six stretto*.json."""
    return {"stretto.json": strict(), "stretto-worker.json": strict_worker(), "stretto2.json": strict(livello=2), "stretto2-worker.json": strict_worker(2),
            "stretto3.json": strict(livello=3), "stretto3-worker.json": strict_worker(3)}


def generati():
    """{file name: content} of every generated file (the two .d.ts and the six stretto*.json)."""
    g, n, _ = genera()
    return {"globali.d.ts": g, "globali-nomi.d.ts": n, **strict_all()}


def main():
    g, n, dove = genera()
    errors = []
    for nome, ps in sorted(dove.items()):
        if len(ps) > 1:
            errors.append("name defined in more than one classic script: %s (%s)" % (nome, ", ".join(ps)))
    inclusi = set(read_list("pagina") + read_list("moduli") + read_list("worker"))
    for p in sorted(glob.glob(ROOT + "/mzlab/web/**/*.js", recursive=True) + glob.glob(ROOT + "/TP_Mine/**/*.js", recursive=True)):
        r = os.path.relpath(p, ROOT)
        if r.startswith(NON_CONTROLLATI) or "/tests/" in r or r in inclusi:
            continue
        errors.append("file in no tsc project (add it to tools/tipi/pagina|moduli|worker.json): " + r)
    if "--controlla" in sys.argv:
        print("\n".join(errors) or "genera_globali: ok")
        return 1 if errors else 0
    for nome, t in generati().items():
        with open(os.path.join(TYPES, nome), "w", encoding="utf8") as f:
            f.write(t)
    print("\n".join(errors))
    return 0


if __name__ == "__main__":
    sys.exit(main())
