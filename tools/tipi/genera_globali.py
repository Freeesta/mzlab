#!/usr/bin/env python3
"""Globals for tsc (job «tipi»): writes tools/tipi/globali.d.ts and globali-nomi.d.ts from the classic scripts listed in pagina.json.

globali.d.ts  = `declare var X: any` for every `window.X = ...` and for the names of the classic scripts that tsc reads as CommonJS (module.exports).
globali-nomi.d.ts = `declare var X: any` for every top-level name of the classic scripts, for the projects that do not include them (moduli, worker).
stretto.json = the files marked `// @ts-strict` (first lines), checked with strictNullChecks: they must have 0 errors.
`--controlla` writes nothing and exits 1 when: a file of mzlab/web or TP_Mine is in no project, a top-level name is defined in two classic scripts,
or the generated files are out of date.
"""
import glob, json, os, re, sys

RADICE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TIPI = os.path.join(RADICE, "tools", "tipi")
NON_CONTROLLATI = ("mzlab/web/vendor/", "mzlab/web/esempi/", "mzlab/web/teoria/", "mzlab/web/wasm/")


def elenco(nome):
    """Source files of a project (paths from the repository root, in the order of the file)."""
    with open(os.path.join(TIPI, nome + ".json")) as f:
        return [p[6:] for p in json.load(f)["include"] if p.startswith("../../")]


def leggi(p):
    with open(os.path.join(RADICE, p), encoding="utf8") as f:
        return f.read()


def nomi_primo_livello(testo):
    ris = set()
    for m in re.finditer(r"^(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)", testo, re.M):
        ris.add(m.group(1))
    for riga in re.finditer(r"^(?:const|let|var)\s[^\n]*", testo, re.M):   # const A = {...}, B = null, C = 0 ...: every name after a value
        for m in re.finditer(r"(?:[}\])]|\bnull|\btrue|\bfalse|\d|[\"'])\s*,\s*([A-Za-z_$][\w$]*)\s*=(?=[^=>])", riga.group(0)):
            ris.add(m.group(1))
    return ris


def manuali():
    return set(re.findall(r"^declare (?:var|const|function|class) ([A-Za-z_$][\w$]*)", leggi("tools/tipi/manuale.d.ts"), re.M))


ASSEGNA = r"\b(?:window|globalThis|self|root)\)?\.([A-Za-z_$][\w$]*)\s*=[^=]"


def genera():
    classici = elenco("pagina")
    finestra, finestra_classici, cjs, dove = set(), set(), set(), {}
    for p in classici:
        t = leggi(p)
        finestra |= set(re.findall(ASSEGNA, t))
        finestra_classici |= set(re.findall(ASSEGNA, t))
        n = nomi_primo_livello(t)
        if re.search(r"\bmodule\.exports\b", t):   # tsc reads these as CommonJS modules: their names are not global for it
            cjs |= n
        for x in n:
            dove.setdefault(x, []).append(p)
    for p in elenco("moduli"):
        finestra |= set(re.findall(ASSEGNA, leggi(p)))
    nel_codice = {x for x, ps in dove.items() if not all(re.search(r"\bmodule\.exports\b", leggi(p)) for p in ps)}
    dichiarati = (finestra | cjs) - nel_codice - manuali()
    testa = "// GENERATED by tools/tipi/genera_globali.py (python3 tools/tipi/genera_globali.py): do not edit.\n"
    g = testa + "".join("declare var %s: any;\n" % x for x in sorted(dichiarati))
    su_window = sorted(finestra_classici & nel_codice - manuali())   # const X ... window.X = X: window.X has the type of X
    if su_window:
        g += "interface Window {\n" + "".join("  %s: typeof %s;\n" % (x, x) for x in su_window) + "}\n"
    n = testa + "".join("declare var %s: any;\n" % x for x in sorted(set(dove) - manuali()))
    return g, n, dove


STRETTO_TESTA = "// @ts-strict"


def stretto():
    """tools/tipi/stretto.json: the files of pagina/moduli with `// @ts-strict` in their first lines, checked with strictNullChecks."""
    files = []
    for p in elenco("pagina") + elenco("moduli"):
        if STRETTO_TESTA in "\n".join(leggi(p).split("\n")[:3]):
            files.append("../../" + p)
    d = {"extends": "./base.json",
         "compilerOptions": {"lib": ["ES2022", "DOM", "DOM.Iterable"], "moduleDetection": "force", "strictNullChecks": True},
         "include": ["globali.d.ts", "globali-nomi.d.ts", "modello.d.ts", "manuale.d.ts", "manuale-dom.d.ts"] + files}
    return json.dumps(d, indent=2) + "\n"


def main():
    g, n, dove = genera()
    st = stretto()
    errori = []
    for nome, ps in sorted(dove.items()):
        if len(ps) > 1:
            errori.append("name defined in more than one classic script: %s (%s)" % (nome, ", ".join(ps)))
    inclusi = set(elenco("pagina") + elenco("moduli") + elenco("worker"))
    for p in sorted(glob.glob(RADICE + "/mzlab/web/**/*.js", recursive=True) + glob.glob(RADICE + "/TP_Mine/**/*.js", recursive=True)):
        r = os.path.relpath(p, RADICE)
        if r.startswith(NON_CONTROLLATI) or "/tests/" in r or r in inclusi:
            continue
        errori.append("file in no tsc project (add it to tools/tipi/pagina|moduli|worker.json): " + r)
    if "--controlla" in sys.argv:
        for nome, atteso in (("globali.d.ts", g), ("globali-nomi.d.ts", n), ("stretto.json", st)):
            try:
                if leggi("tools/tipi/" + nome) != atteso:
                    errori.append(nome + " out of date: run python3 tools/tipi/genera_globali.py")
            except OSError:
                errori.append(nome + " missing")
        print("\n".join(errori) or "genera_globali: ok")
        return 1 if errori else 0
    for nome, t in (("globali.d.ts", g), ("globali-nomi.d.ts", n), ("stretto.json", st)):
        with open(os.path.join(TIPI, nome), "w", encoding="utf8") as f:
            f.write(t)
    print("\n".join(errori))
    return 0


if __name__ == "__main__":
    sys.exit(main())
