fn same(what: &str, z: u8, a: &[f64], b: &[f64]) {
    for (x, y) in a.iter().zip(b) {
        assert!(
            (x - y).abs() <= 1e-9 * y.abs().max(1.0),
            "Z={z} {what}: sci-form {x} dxtb {y}"
        );
    }
}

#[test]
fn element_parameters_as_dxtb() {
    for (z, levels, slater, refocc, shpoly, kcn, lgam, g) in DXTB {
        let p = get_gfn2_params(z).unwrap();
        let n = levels.len();
        assert_eq!(p.nshell, n, "Z={z} shells");
        same("levels", z, &p.selfenergy[..n], levels);
        same("slater", z, &p.slater[..n], slater);
        same("refocc", z, &p.ref_occ[..n], refocc);
        same("shpoly", z, &p.shpoly[..n], shpoly);
        same("kcn", z, &p.kcn[..n], kcn);
        same("lgam", z, &p.shell_hubbard[..n], lgam);
        // sci-form has mprad 3.9 for Br; `xtb/aes.rs` uses 4.0 as dxtb (charges of bromobenzene as tblite within 6e-6 with 4.0, 4e-4 with 3.9).
        let mp_rad = if z == 35 { 4.0 } else { p.mp_rad };
        let atom = [
            p.hubbard,
            p.gam3,
            p.pauling_en,
            p.dkernel,
            p.qkernel,
            mp_rad,
            p.mp_vcn,
            p.rep_zeff,
            p.rep_alpha,
        ];
        same(
            "gam, gam3, en, dkernel, qkernel, mprad, mpvcn, zeff, arep",
            z,
            &atom,
            &g,
        );
    }
}

#[test]
fn global_parameters_as_dxtb() {
    // [hamiltonian.xtb.shell] ss, pp, dd, sd, pd; enscale; [thirdorder.shell] s, p, d.
    same(
        "kshell",
        0,
        &[
            kshell_factor(0, 0),
            kshell_factor(1, 1),
            kshell_factor(2, 2),
            kshell_factor(0, 2),
            kshell_factor(1, 2),
        ],
        &[1.85, 2.23, 2.23, 2.0, 2.0],
    );
    same("enscale", 0, &[ENSCALE], &[0.02]);
    same(
        "gam3 shell",
        0,
        &[GAM3_SHELL[0][0], GAM3_SHELL[1][0], GAM3_SHELL[2][0]],
        &[1.0, 0.5, 0.25],
    );
}
