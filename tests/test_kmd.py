"""Kendrick mass defect parity tests: frozen responses in tests/golden/kmd.json, units in kmd-calc.js, and pure-Rust engine."""
import json
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "mzlab" / "web"
GOLDEN = json.loads((ROOT / "tests" / "golden" / "kmd.json").read_text())


@pytest.mark.skipif(shutil.which("node") is None, reason="node is not installed")
def test_the_units_have_the_exact_masses():
    out = subprocess.run(
        ["node", "-e", f"const K=require({str(WEB / 'kmd-calc.js')!r});console.log(JSON.stringify(K.UNITS.map(u => [u.id, +u.mass.toFixed(5), u.nominal])))"],
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    ).stdout
    r = json.loads(out)
    assert r == [["CF2", 49.99681, 50], ["CF2O", 65.99172, 66], ["C2F4", 99.99361, 100], ["CH2", 14.01565, 14]]


def test_a_homologous_series_has_one_kmd_and_a_retention_trend():
    case = GOLDEN["series"]
    assert len(case["series"]) == 1
    s = case["series"][0]
    assert s["members"] == list(range(7)) and s["distinct"] == 7 and s["steps"] == [1] * 6 and s["consecutive"] == 1
    assert s["spanMDa"] < 1.0 and s["rho"] > 0.99
    feats = case["input"]["features"]
    assert all(x["series"] is None for x in case["rows"] if feats[x["i"]]["id"] in (98, 99)), "unrelated ions never join the series"


def test_a_missing_member_shows_as_a_step_of_two_and_a_short_series_is_not_reported():
    gap = GOLDEN["gap"]
    assert gap["series"][0]["steps"] == [1, 2, 1] and abs(gap["series"][0]["consecutive"] - 2 / 3) < 1e-9
    short = GOLDEN["short"]
    assert short["series"] == [] and all(x["series"] is None for x in short["rows"])


def test_another_unit_regroups_the_same_ions():
    ch2 = GOLDEN["ch2"]
    assert len(ch2["series"]) == 1
    s = ch2["series"][0]
    assert s["distinct"] == 6 and s["rho"] is not None and s["rho"] > 0.99
    assert ch2["rows"][6]["series"] is None


def test_the_rust_golden_is_what_the_reference_gives():
    """`tests/golden/kmd.json` (read by `crates/mzlab-core/tests/kendrick_parity.rs`) is regenerated by `tools/kmd_riferimento.py`, never by hand."""
    assert subprocess.run(["python3", str(ROOT / "tools" / "kmd_riferimento.py"), "--check"]).returncode == 0
